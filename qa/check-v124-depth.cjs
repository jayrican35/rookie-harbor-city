'use strict';
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path'),assert=require('node:assert/strict');
const dir=path.resolve(__dirname,'..','published-game-capture');
const s=fs.readFileSync(path.join(dir,'v116-marina.js'),'utf8');
const city=fs.readFileSync(path.join(dir,'v115-campus.js'),'utf8');
const queue=city.slice(city.indexOf('function drawEntityHighlights('),city.indexOf('function paint(t,dt)'));
const foreground=s.slice(s.indexOf('function foreground('),s.indexOf('function waterBlocked('));
assert(s.includes('function depthProps(view)')&&s.includes('function drawDepthProp(g,entry,opt,t)'));
assert(s.includes('background:begin,foreground,depthProps,drawDepthProp'));
assert(queue.includes('marina.depthProps(view)'));
assert(queue.includes('entries.push({y:prop.depthY,depthProp:prop})'));
assert(queue.includes('marina.drawDepthProp(g,entry.depthProp,'));
assert(queue.includes('entries.sort((a,b)=>a.y-b.y)'));
assert(!foreground.includes('for(const b of interiors)if(b.roof'), 'Never draw roofs over Jay in final pass');
assert(!foreground.includes("o.type==='lamp'"),'Never draw lamps over Jay in final pass');
assert(!foreground.includes("paintSprite(g,o.image,-o.w/2,-o.h,o.w,o.h)"),'Tall trees must be sorted too');
assert(s.includes('const withinDoor=Math.abs(player.x-b.door.x)'),'Only true doors reveal rooms');
const mock={window:{},Image:function(){return {complete:true,naturalWidth:256,naturalHeight:256}},
 document:{readyState:'loading',addEventListener(){}},location:{search:''},Math,Map,Set,Object,Array,JSON,Number,console,performance:{now:()=>0}};
vm.runInNewContext(s,mock);
const m=mock.window.ROOKIE_V116_MARINA;
const view={x:4400,y:3220,w:1500,h:900};
const objs=m.depthProps(view);
const lamps=objs.filter(p=>p.kind==='tall'&&p.object.type==='lamp');
const trees=objs.filter(p=>p.kind==='tall'&&p.object.type==='tree');
const roofs=objs.filter(p=>p.kind==='roof');
assert.equal(lamps.length,5);
assert(trees.length>=10);
assert.equal(roofs.length,4);
const lamp=lamps.find(p=>p.object.x===5060);
assert(lamp&&lamp.depthY===5060*0+3655+85-3);
assert(3760>lamp.depthY,'Jay in front draws AFTER lamp');
assert(3700<lamp.depthY,'Jay behind draws BEFORE lamp');
const office=m.interiors.find(b=>b.id==='marina:office');
const roof=roofs.find(p=>p.building===office);
assert(roof&&roof.depthY<3582,'Jay on frontage must draw in front of roof');
for(let i=0;i<60;i++)m.updateInteriors({x:office.door.x+office.door.w/2+20,y:office.door.y+9},.05);
assert(office.roof>.99,'Adjacent to a wall outside doorway must keep roof fully visible');
for(let i=0;i<60;i++)m.updateInteriors({x:office.door.x,y:office.door.y+12},.05);
assert(office.roof<.01,'Correct doorway threshold reveals the room');
for(let i=0;i<60;i++)m.updateInteriors({x:office.door.x,y:office.door.y+37},.05);
assert(office.roof>.99,'Leaving doorway restores roof');
assert(m.blocksProp(5000,3920),'Water must remain blocked');
assert(!m.blocksProp(5150,3920),'Pier center must remain walkable');
assert.equal(m.metrics().zombieOutbreakModified,false);
console.log('PASS V124: shared y-sorting for lamp/roof/tree, front-vs-back depth behavior, true doorway roof trigger, preserved original walking and Zombie mode');
